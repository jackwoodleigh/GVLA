"""
eval_open_loop.py

Open-loop evaluation of VLA-Adapter on collected Franka demo episodes.

What this does:
  For each recorded timestep in each demo, we feed the camera images and
  robot state into the policy and record what action it would predict.
  We then compare those predictions to what the human actually did,
  as a sanity check before running the policy on the real robot.

Note: this is NOT a closed-loop rollout. The policy sees the human's
observations (not observations it would have generated by acting), so
we can't guarantee real-robot success — but erratic or backwards
predictions here are a definite red flag.

Run with:
    sbatch experiments/robot/franka/run_eval.sh
(from the GVLA root directory)
"""


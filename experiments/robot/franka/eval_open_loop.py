# ==============================================================================
# Data loading
# ==============================================================================

def load_episode(episode_path: Path):
    """
    Load all data for one demo episode.

    Returns:
        proprio     : (T, 8) float64 — EEF pos (3) + axis-angle (3) + gripper 2D (2),
                      matching the representation the policy was trained on (LIBERO format)
        pose        : (T, 7) float64 — EEF position (xyz) + quaternion (xyzw) in robot base frame
        grasp       : (T,)   int32   — binary grasp signal (0=open, 1=closed)
        cam3_frames : sorted list of Path to cam3 (scene) rgb images
        cam4_frames : sorted list of Path to cam4 (wrist) rgb images
    """
    state_dir = episode_path / "state"

    gripper_qpos = np.load(state_dir / "gripper_qpos.npy")   # (T,): scalar in [0,1]
    pose         = np.load(state_dir / "pose_wrt_world.npy") # (T, 7): xyz + quat (xyzw)
    grasp        = np.load(state_dir / "grasp.npy")          # (T,): binary

    proprio = np.stack([
        build_libero_proprio(pose[t, :3], pose[t, 3:7], gripper_qpos[t])
        for t in range(len(pose))
    ])

    # Sort frames by filename — filenames are nanosecond timestamps, so
    # sorted alphabetically = sorted chronologically
    cam3_frames = sorted((episode_path / "cam3" / "rgb").glob("*.png"))
    cam4_frames = sorted((episode_path / "cam4" / "rgb").glob("*.png"))

    assert len(cam3_frames) == len(cam4_frames) == len(proprio), (
        f"Frame/state count mismatch in {episode_path.name}: "
        f"cam3={len(cam3_frames)}, cam4={len(cam4_frames)}, state={len(proprio)}"
    )

    return proprio, pose, grasp, cam3_frames, cam4_frames


def compute_actual_deltas(pose: np.ndarray, grasp: np.ndarray) -> np.ndarray:
    """
    Compute what the human actually did at each timestep, expressed as
    delta end-effector position and gripper state.

    The VLA policy predicts 7-dim actions: [dx, dy, dz, droll, dpitch, dyaw, gripper].
    We compute [dx, dy, dz] from consecutive EEF positions, and gripper from grasp.npy.
    (We skip rotation for simplicity — harder to visualize and less critical for a sanity check.)

    Returns:
        (T-1, 4) array: [delta_x, delta_y, delta_z, gripper]
    """
    delta_pos = pose[1:, :3] - pose[:-1, :3]       # (T-1, 3)
    gripper   = grasp[:-1].astype(np.float32)       # (T-1,)
    return np.concatenate([delta_pos, gripper[:, None]], axis=1)


# ==============================================================================
# Inference
# ==============================================================================

def run_episode(cfg, episode_path, model, processor, action_head, proprio_projector):
    """
    Run the policy on one episode using proper action chunking.

    The policy is queried every NUM_ACTIONS_CHUNK steps (default 8). Each query
    returns a full chunk of predicted actions, which we unroll for those 8 steps.
    This matches real deployment and avoids per-step spikiness from re-querying.

    Returns:
        predicted : (T, 7)   — policy's predicted 7-dim delta action at each timestep
        actual    : (T-1, 4) — actual [dx, dy, dz, gripper] from the demo
    """
    proprio, pose, grasp, cam3_frames, cam4_frames = load_episode(episode_path)
    T = len(cam3_frames)

    predicted_actions = []
    action_queue = []   # holds the unexecuted actions from the last chunk

    for t in range(T):
        # Re-query the policy when the action queue is empty
        if len(action_queue) == 0:
            scene_img = np.array(Image.open(cam3_frames[t]).convert("RGB"))
            wrist_img = np.array(Image.open(cam4_frames[t]).convert("RGB"))

            obs = {
                "full_image":  scene_img,   # cam3: front-facing scene (≈ LIBERO agentview)
                "wrist_image": wrist_img,   # cam4: wrist camera — key must contain "wrist"
                "state":       proprio[t],  # 8-dim: 7 joints + gripper
            }

            # get_action returns a list of NUM_ACTIONS_CHUNK action arrays
            actions = get_action(
                cfg, model, obs, cfg.task_instruction,
                processor=processor,
                action_head=action_head,
                proprio_projector=proprio_projector,
                use_minivlm=cfg.use_minivlm,
            )

            # Flip gripper convention: model outputs 0=open,1=closed; demo uses 0=closed,1=open
            actions = [flip_gripper(a) for a in actions]
            action_queue.extend(actions)
            print(f"  t={t:3d}/{T}  queried policy, chunk[0][:3]={actions[0][:3].round(4)}")

        predicted_actions.append(action_queue.pop(0))

    predicted_osc = np.stack(predicted_actions)        # (T, 7) — LIBERO OSC units
    actual        = compute_actual_deltas(pose, grasp) # (T-1, 4) — meters

    # Convert translation and rotation to approximate meters/radians.
    # Gripper (dim 6) is left untouched — it is binary 0/1, no scaling needed.
    # Uses robosuite default OSC gains — sim approximation, not exact.
    predicted_meters = predicted_osc.copy()
    predicted_meters[:, :3]  = predicted_osc[:, :3]  * LIBERO_OSC_TRANSLATION_SCALE
    predicted_meters[:, 3:6] = predicted_osc[:, 3:6] * LIBERO_OSC_ROTATION_SCALE

    return predicted_meters, actual


# ==============================================================================
# Plotting
# ==============================================================================

def plot_episode(episode_name, predicted, actual, results_dir):
    """
    Plot predicted vs actual delta actions in meters.

    Both signals are in the same unit (meters for translation, 0/1 for gripper)
    so magnitude differences are directly visible.

    predicted : (T, 7)   — policy output converted to meters via libero_osc_to_meters
    actual    : (T-1, 4) — [dx, dy, dz, gripper] in meters from demo
    """
    T_pred = predicted.shape[0]
    T_act  = actual.shape[0]
    t_pred = np.linspace(0, 1, T_pred)
    t_act  = np.linspace(0, 1, T_act)

    fig, axes = plt.subplots(4, 1, figsize=(13, 10), sharex=True)
    fig.suptitle(
        f"Open-loop eval — {episode_name}\n"
        "Both signals in meters (predicted via OSC×0.05 approx)  |  x-axis = normalized time",
        fontsize=10,
    )

    axis_labels = ["delta_x (m)", "delta_y (m)", "delta_z (m)"]
    for i, label in enumerate(axis_labels):
        axes[i].plot(t_pred, predicted[:, i], color="steelblue", label="predicted", linewidth=1.2)
        axes[i].plot(t_act,  actual[:, i],    color="coral",     label="actual",    linewidth=1.2, linestyle="--")
        axes[i].set_ylabel(label, fontsize=9)
        axes[i].axhline(0, color="gray", linewidth=0.5, linestyle=":")
        axes[i].legend(fontsize=8)

    # Gripper: both on [0, 1] scale
    axes[3].plot(t_pred, predicted[:, 6], color="steelblue", label="predicted gripper", linewidth=1.2)
    axes[3].plot(t_act,  actual[:, 3],    color="coral",     label="actual grasp",      linewidth=1.2, linestyle="--")
    axes[3].set_ylabel("gripper (0=close, 1=open)", fontsize=9)
    axes[3].set_xlabel("normalized time (0=start, 1=end)", fontsize=9)
    axes[3].legend(fontsize=8)
    axes[3].set_ylim(-0.1, 1.1)

    plt.tight_layout()
    out_path = Path(results_dir) / f"{episode_name}.png"
    plt.savefig(out_path, dpi=130)
    plt.close()
    print(f"  Saved plot → {out_path}")


# ==============================================================================
# Main
# ==============================================================================

def main():
    cfg = EvalConfig()
    set_seed_everywhere(cfg.seed)
    os.makedirs(cfg.results_dir, exist_ok=True)

    print("=" * 60)
    print("Open-loop VLA-Adapter eval on Franka demos")
    print(f"Checkpoint : {cfg.pretrained_checkpoint}")
    print(f"Instruction: {cfg.task_instruction}")
    print(f"Episodes   : {cfg.episodes_dir}")
    print(f"Results    : {cfg.results_dir}")
    print("=" * 60)

    # --- Load model ---
    print("\nLoading model (this takes ~30s)...")
    model = get_model(cfg)
    model.set_version(cfg.save_version)

    # num_task_tokens is required by the action head / proprio projector
    NUM_PATCHES = (
        model.vision_backbone.get_num_patches()
        * model.vision_backbone.get_num_images_in_input()
    )
    if cfg.use_proprio:
        NUM_PATCHES += 1
    cfg.num_task_tokens = NUM_PATCHES

    proprio_projector = get_proprio_projector(cfg, model.llm_dim, proprio_dim=8)
    action_head       = get_action_head(cfg, model.llm_dim)
    processor         = get_processor(cfg)
    print("Model loaded.\n")

    # --- Run all episodes ---
    episodes = sorted(Path(cfg.episodes_dir).iterdir())
    print(f"Found {len(episodes)} episodes\n")

    summary_rows = []

    for ep_path in episodes:
        if not ep_path.is_dir():
            continue
        print(f"--- {ep_path.name} ---")
        predicted, actual = run_episode(cfg, ep_path, model, processor, action_head, proprio_projector)
        plot_episode(ep_path.name, predicted, actual, cfg.results_dir)

        mean_pred_mag = np.abs(predicted[:, :3]).mean(axis=0)
        mean_act_mag  = np.abs(actual[:, :3]).mean(axis=0)
        summary_rows.append({
            "episode": ep_path.name,
            "predicted_xyz_mag": mean_pred_mag,
            "actual_xyz_mag":    mean_act_mag,
        })
        print(f"  Mean |predicted xyz| (m, OSC×0.05): {mean_pred_mag.round(5)}")
        print(f"  Mean |actual    xyz| (m):            {mean_act_mag.round(5)}")

    # --- Summary ---
    print("\n" + "=" * 60)
    print("SUMMARY")
    print("=" * 60)
    for row in summary_rows:
        print(f"  {row['episode']}")
        print(f"    predicted xyz mag (m, OSC×0.05): {row['predicted_xyz_mag']}")
        print(f"    actual    xyz mag (m):            {row['actual_xyz_mag']}")

    # Save raw arrays for further analysis if needed
    np.save(Path(cfg.results_dir) / "all_predicted.npy",
            np.array([r["predicted_xyz_mag"] for r in summary_rows]))
    print(f"\nDone. Plots and arrays saved to {cfg.results_dir}")


if __name__ == "__main__":
    main()
